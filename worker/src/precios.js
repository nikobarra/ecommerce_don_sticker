// Total de los stickers a elección: la cantidad completa toma el precio por unidad de su tramo.
export const totalSueltos = (cantidad, pago) => {
  const lista = cantidad * precioUnitarioLista(cantidad);
  return esTransferencia(pago) ? aTransferencia(lista) : lista;
};
// Precio por unidad (solo para mostrar en el detalle): total del tramo / cantidad.
export const precioSuelto = (cantidad, pago) => (cantidad > 0 ? Math.round(totalSueltos(cantidad, pago) / cantidad) : precioUnitarioLista(1));

// Arma y valida el detalle de un pedido con el medio de pago elegido.
// Devuelve { ok, items, subtotal, subtotalLista, descuento, stickers, sueltos } o { ok:false, mensaje }.
export function armarDetalle(itemsPedidos, pago = "transferencia") {
  if (!Array.isArray(itemsPedidos) || !itemsPedidos.length) return { ok: false, mensaje: "El pedido está vacío." };
  if (itemsPedidos.length > 60) return { ok: false, mensaje: "El pedido tiene demasiados productos distintos." };
  const cantidades = new Map();
  for (const it of itemsPedidos) {
    const id = String(it?.id ?? "");
    const n = Number(it?.cantidad);
    if (!Number.isInteger(n) || n < 1 || n > 999) return { ok: false, mensaje: "Hay una cantidad que no es válida." };
    cantidades.set(id, (cantidades.get(id) || 0) + n);
  }
  const items = [];
  let sueltos = 0;
  let totalPacks = 0;
  let totalPacksLista = 0;
  let stickers = 0;
  for (const [id, cantidad] of cantidades) {
    const pack = PACKS.find((p) => p.id === id);
    const prod = PRODUCTOS.find((p) => p.id === id);
    if (pack) {
      const precio = esTransferencia(pago) ? pack.precioTransferencia : pack.precio;
      items.push({ id, nombre: pack.nombre, cantidad, tipo: "pack", unidades: pack.unidades, precio, precioLista: pack.precio,
        disenos: [...(PACKS_CONTENIDO[id] || [])] });
      totalPacks += precio * cantidad;
      totalPacksLista += pack.precio * cantidad;
      stickers += pack.unidades * cantidad;
    } else if (prod) {
      items.push({ id, nombre: prod.nombre, codigo: id.toUpperCase(), cantidad, tipo: "suelto" });
      sueltos += cantidad;
      stickers += cantidad;
    } else {
      return { ok: false, mensaje: "Hay un producto que ya no está disponible." };
    }
  }
  const unitario = precioSuelto(sueltos, pago);
  const unitarioLista = precioUnitarioLista(sueltos);
  for (const it of items) if (it.tipo === "suelto") { it.precio = unitario; it.precioLista = unitarioLista; }
  const subtotal = totalPacks + totalSueltos(sueltos, pago);
  const subtotalLista = totalPacksLista + totalSueltos(sueltos, "mercadopago");
  return { ok: true, items, subtotal, subtotalLista, descuento: subtotalLista - subtotal, stickers, sueltos };
}

// Tarifa de respaldo según provincia: precio fijo por zona.
export function tarifaRespaldo(provincia, stickers) {
  const prov = ENVIO.provincias.find((p) => p.nombre === provincia);
  if (!prov) return null;
  const z = ENVIO.zonas.find((x) => x.zona === prov.zona);
  return z ? { precio: z.precio, gramos: stickers * ENVIO.gramosPorSticker + ENVIO.gramosEmbalaje } : null;
}
